"""Provider-neutral adapter contracts for real local integrations."""

from typing import Protocol
from .models import EmailMessage, TextMessage


class EmailAdapter(Protocol):
    def check_connection(self) -> None: ...
    def search(self, query: str, limit: int = 20) -> list[EmailMessage]: ...
    def get(self, message_id: str) -> EmailMessage: ...
    def recent(self, max_age_seconds: int = 300) -> list[EmailMessage]: ...


class MessageAdapter(Protocol):
    def search(
        self, query: str, conversation_scope: str = "*", limit: int = 20
    ) -> list[TextMessage]: ...
    def get(self, message_id: str) -> TextMessage: ...
    def list_conversations(self) -> list[dict]: ...


class Keychain(Protocol):
    def get_secret(self, service: str, account: str) -> bytes | None: ...
    def set_secret(self, service: str, account: str, value: bytes) -> None: ...
